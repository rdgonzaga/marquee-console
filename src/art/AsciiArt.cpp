std::vector<std::string> render(const std::string& text) {
    std::vector<std::string> rows(GLYPH_HEIGHT);
    for (unsigned char c : text) {
        int index = c - FIRST_CHAR;
        if (index < 0 || index >= GLYPH_COUNT) continue;
        for (int r = 0; r < GLYPH_HEIGHT; ++r) rows[r] += GLYPHS[index][r];
    }
    return rows;
}

std::vector<std::string> split(const char* art) {
    std::vector<std::string> rows;
    std::istringstream in(art);
    std::string line;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r') line.pop_back();
        rows.push_back(line);
    }
    return rows;
}

